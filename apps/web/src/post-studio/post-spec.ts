/**
 * Скільки позначених `data-reveal` елементів уже видно на момент t.
 *
 * Відкриваються рівномірно, а не всі одразу: готовий список глядач
 * прочитає до того, як про нього скажуть, і далі слухатиме вже без
 * інтересу. Останню чверть відрізка тримаємо на повному складі — щоб
 * фінальний рядок встиг прочитатись.
 */
export function cardRevealCount(total: number, hold: number, start: number, t: number): number {
  if (total <= 0) return 0;
  const fill = Math.max(0.001, hold * 0.75);
  const k = Math.floor(((t - start) / fill) * total) + 1;
  return Math.max(1, Math.min(total, k));
}

/** Активна картка на позиції t. Двох одночасно не буває — вони широкі. */
export function cardAt(
  cards: readonly Card[],
  words: readonly WordTiming[],
  t: number,
): { card: Card; start: number; end: number } | null {
  const spans = cards
    .filter((c) => words[c.word] != null && c.hold > 0)
    .map((c) => ({ card: c, start: words[c.word]!.start, end: words[c.word]!.start + c.hold }))
    .sort((a, b) => a.start - b.start);
  // Остання з тих, що вже почались і ще не скінчились: якщо агент
  // накидав карток внахлест, у кадрі буде найсвіжіша, а не найстаріша.
  let found: { card: Card; start: number; end: number } | null = null;
  for (const s of spans) {
    if (s.start <= t && t < s.end) found = s;
  }
  return found;
}

/** Скільки стікерів максимум тримаємо в кадрі одночасно. */
export const STICKER_MAX_LIVE = 5;

/** Скільки триває згасання наприкінці власного відрізка стікера. */
export const STICKER_EXIT_LEAD_S = 0.4;

/**
 * Вихід картки й стікера — так само чиста функція часу, як і вхід.
 *
 * Раніше картка просто зникала разом зі своїм інтервалом, а стікер
 * гаснув за 0.15 с. У кадрі це читалось як склейка: одне щезло, друге
 * стало. Тепер попереднє встигає піти рухом — опуститись і стиснутись, —
 * і око встигає за переходом.
 */
export const CARD_IN_S = 0.42;
export const CARD_OUT_S = 0.4;

export function cardMotion(
  age: number,
  hold: number,
): { x: number; y: number; scale: number; opacity: number } {
  const left = hold - age;
  if (left <= CARD_OUT_S) {
    const q = smooth(Math.min(Math.max(1 - left / CARD_OUT_S, 0), 1));
    return { x: 0, y: -3 * q, scale: 1 - 0.05 * q, opacity: 1 - q };
  }
  const p = Math.min(Math.max(age / CARD_IN_S, 0), 1);
  const e = easeOut(p);
  // Приїзд СПРАВА: картка в'їжджає з-за правого краю з невеликим
  // проскоком (як бічний вхід стікера) — рух іззовні читається як
  // «прийшла нова річ», а не як підміна кадру. Без проявлення:
  // напівпрозора картка читається як недомальована.
  const x = p < 0.72
    ? 120 * (1 - easeOut(p / 0.72))
    : -2 + 2 * smooth((p - 0.72) / 0.28);
  // Вхід — РІВНА горизонталь. Був ще підйом `2 * (1 - e)`: картка
  // стартувала на 2 % нижче й дотягувалась угору, і разом із проскоком
  // по X виходила дуга. Поки картка їхала сама, це читалось як осідання;
  // з подарунком у слоті — як два предмети, що сходяться в кадрі.
  // Догори картка йде тільки на ВИХОДІ (гілка вище), і там це доречно:
  // вона звільняє місце наступному носію.
  return { x, y: 0, scale: 0.97 + 0.03 * e, opacity: 1 };
}

/**
 * Розкладка стікерів у часі: абсолютні межі з `word` і `hold`.
 *
 * Перекриття НЕ підрізаємо. Раніше кінець кожного стікера обрізався
 * початком наступного — «два в кадрі одночасно не тримай». Виявилось,
 * що саме накопичення й дає сенс: перший стікер лишається, поруч стає
 * другий, і кадр перетворюється на маленьку схему замість карусельки
 * окремих картинок. Скільки їх видно разом, вирішує вже розкладка.
 *
 * Порядок сортується за часом, а не за позицією в масиві: агент дописує
 * стікери в кінець списку, і покладатись на порядок запису не можна.
 */
/**
 * Пороги розмітки речень.
 *
 * Ділити за крапками НЕ можна: озвучка не збігається з пунктуацією —
 * диктор тримає паузу там, де коми немає, і проскакує крапку, коли
 * фраза йде на одному подиху. Тому головне джерело меж — тиша між
 * словами, а розділовий знак лише знижує поріг.
 */
export const SCENE_PAUSE_HARD_S = 0.42;
export const SCENE_PAUSE_SOFT_S = 0.24;
/** Коротше — не думка, а хвіст попередньої. */
export const SCENE_MIN_S = 2.2;
/** Довше — вже не одна думка, ріжемо примусово. */
export const SCENE_MAX_S = 7;

/**
 * Нарізка доріжки на речення за паузами.
 *
 * Результат — чернетка, а не істина: межі мусять лишатись правними
 * руками, бо помилка тут отруює все, що нижче (група картинок, рух,
 * бриф на генерацію).
 */
export function sliceScenes(words: readonly WordTiming[]): Scene[] {
  if (words.length === 0) return [];
  const scenes: Scene[] = [];
  let from = 0;
  for (let i = 0; i < words.length - 1; i += 1) {
    const cur = words[i]!;
    const next = words[i + 1]!;
    const gap = next.start - cur.end;
    const dur = cur.end - words[from]!.start;
    // Одне-двоє слів реченням не бувають — крім випадку, коли після них
    // справжня тиша. «Слухай.» перед паузою в пів секунди це таки окрема
    // думка, а не хвіст; поріг тут вищий за звичайний саме тому, що
    // короткій фразі треба сильніший доказ межі.
    if (dur < 1 && gap < 0.6) continue;
    const punctuated = /[.!?…:]$/.test(cur.word.trim());
    const hard = gap >= SCENE_PAUSE_HARD_S;
    const soft = gap >= SCENE_PAUSE_SOFT_S && dur >= SCENE_MIN_S;
    const byPunct = punctuated && gap >= SCENE_PAUSE_SOFT_S * 0.6 && dur >= SCENE_MIN_S;
    // Мова без пауз теж буває — на швидкому темпі диктор іде суцільно.
    // Тоді спершу пробуємо найдрібнішу щілину, а на межі ріжемо вже
    // беззастережно: тринадцятисекундна «думка» гірша за розріз посеред
    // фрази, бо під неї не підібрати ні картинки, ні руху.
    const stretched = dur >= SCENE_MAX_S * 0.8 && gap >= 0.08;
    const tooLong = dur >= SCENE_MAX_S;
    if (hard || soft || byPunct || stretched || tooLong) {
      scenes.push({ from, to: i });
      from = i + 1;
    }
  }
  scenes.push({ from, to: words.length - 1 });
  return scenes;
}

/** Межі речення в секундах — рахуються з `words`, а не зберігаються. */
export function sceneSpan(
  scene: Scene,
  words: readonly WordTiming[],
): { start: number; end: number } {
  const first = words[scene.from];
  const last = words[scene.to];
  return { start: first?.start ?? 0, end: last?.end ?? 0 };
}

/** Текст речення — так само виводиться, щоб не розійтись із доріжкою. */
export function sceneText(scene: Scene, words: readonly WordTiming[]): string {
  return words
    .slice(scene.from, scene.to + 1)
    .map((w) => w.word)
    .join(' ');
}

/** Яке речення звучить на позиції t. */
export function sceneAt(
  scenes: readonly Scene[],
  words: readonly WordTiming[],
  t: number,
): { scene: Scene; index: number } | null {
  for (let i = 0; i < scenes.length; i += 1) {
    const s = scenes[i]!;
    const { start, end } = sceneSpan(s, words);
    if (t >= start && t < end) return { scene: s, index: i };
  }
  return null;
}

/**
 * Проміжок між тим, як пішов один предмет, і тим, як заходить наступний.
 * Рівно стільки, щоб вихід догорів у порожньому кадрі.
 */
const CARRIER_GAP_S = 0.12;

/** Чи належать дві сцени одній думці (ланцюг `continues: true`). */
function sameThought(scenes: readonly Scene[], a: number, b: number): boolean {
  if (a === b) return true;
  if (a < 0 || b < 0) return false;
  const lo = Math.min(a, b);
  const hi = Math.max(a, b);
  for (let k = lo + 1; k <= hi; k += 1) {
    if (scenes[k]?.continues !== true) return false;
  }
  return true;
}

/** Індекс сцени, у чий діапазон слів потрапляє це слово. */
function sceneOfWord(scenes: readonly Scene[], wordIndex: number): number {
  return scenes.findIndex((s) => wordIndex >= s.from && wordIndex <= s.to);
}

/**
 * Життя предметів у часі.
 *
 * `hold` задає агент, але предмет не може дожити до приходу СЛІДУЮЧОЇ
 * думки. Доти міг: стікер попереднього речення ще висів, коли заходив
 * наступний, обидва потрапляли в одну розкладку і РОЗʼЇЖДЖАЛИСЯ,
 * звільняючи місце. Задумано це було для двох предметів однієї думки, а
 * між різними думками читалось як політ з краю в край на зламі фрази.
 *
 * Стеля саме «до наступного носія», а не «до кінця речення». Різниця не
 * теоретична: за кінцем речення предмет із бейджами на 9-й і 11-й
 * секунді помирав на 8-й, і плашки не з'являлись зовсім — мовчки, бо
 * малюються вони всередині предмета. За приходом наступного той самий
 * предмет живе, скільки просив, і ріжеться лише там, де інакше був би
 * перетин.
 *
 * Носій — і стікер, і картка: картка теж займає ту саму смугу кадру.
 *
 * Одна думка (ланцюг `continues: true`) стелі не створює: там два
 * предмети поруч — свідома схема, і розсування доречне.
 */
export function stickerSpans(
  stickers: readonly Sticker[],
  words: readonly WordTiming[],
  scenes: readonly Scene[] = [],
  cards: readonly Card[] = [],
): { sticker: Sticker; start: number; end: number }[] {
  const alive = stickers.filter((s) => words[s.word] != null && s.hold > 0);

  // Усі носії за часом появи — щоб знати, хто заходить наступним.
  const carriers = [
    ...alive.map((s) => ({
      start: Math.max(0, words[s.word]!.start - (s.lead ?? 0)),
      scene: sceneOfWord(scenes, s.word),
    })),
    ...cards
      .filter((c) => words[c.word] != null && c.hold > 0)
      .map((c) => ({ start: words[c.word]!.start, scene: sceneOfWord(scenes, c.word) })),
  ].sort((a, b) => a.start - b.start);

  return alive
    .map((s) => {
      const start = Math.max(0, words[s.word]!.start - (s.lead ?? 0));
      const asked = words[s.word]!.start + s.hold;
      if (scenes.length === 0) return { sticker: s, start, end: asked };

      const mine = sceneOfWord(scenes, s.word);
      const next = carriers.find(
        (c) => c.start > start && !sameThought(scenes, mine, c.scene),
      );
      if (!next) return { sticker: s, start, end: asked };
      // Стеля не може зробити життя коротшим за появу: інакше предмет
      // народжується вже вмираючим.
      const end = Math.max(start + 0.2, Math.min(asked, next.start - CARRIER_GAP_S));
      return { sticker: s, start, end };
    })
    .sort((a, b) => a.start - b.start);
}

/**
 * Хто зараз у кадрі і де саме стоїть.
 *
 * Місце НЕ зберігається в даних, а рахується щоразу з кількості живих
 * стікерів. Записаний вручну бік («ліворуч») бреше, щойно поруч
 * зʼявиться третій: два стікери стоять по краях, три — по третинах, і
 * жодна стала позиція під це не підходить.
 *
 * Ширина падає разом із кількістю, інакше пʼять по 42 % не влізуть у
 * кадр. Мінімум узятий такий, щоб предмет ще читався силуетом.
 */
export function stickerLayout(
  spans: readonly { sticker: Sticker; start: number; end: number }[],
  t: number,
  maxWidthPct: number,
): { sticker: Sticker; start: number; end: number; left: number; width: number }[] {
  // Найсвіжіші важливіші: якщо агент поставив забагато, у кадрі лишиться
  // те, що прозвучало щойно, а не те, що вже давно висить.
  const live = spans.filter((s) => t >= s.start && t < s.end).slice(-STICKER_MAX_LIVE);
  const n = live.length;
  if (n === 0) return [];
  // Що більше предметів, то дрібніший кожен. Один предмет це подія, троє
  // це схема: схему око охоплює цілком, тому її частини мають бути
  // меншими за самотній предмет, інакше кадр розпирає.
  // Одиночний навмисно більший за максимум пари: сам у кадрі предмет
  // має важити, і розмір у нього завжди той самий, скільки б разів
  // він не зʼявлявся сам.
  const SHRINK = [1, 1.12, 0.8, 0.66, 0.58, 0.52];

  /**
   * Розмір беремо з ПІКОВОЇ кількості сусідів за все життя стікера, а не
   * з поточної. Інакше поява другого змушувала перший міняти розмір
   * прямо в кадрі, і рух виходив подвійним: їде вбік і водночас меншає.
   * Тепер предмет народжується вже потрібного розміру і тільки їде.
   */
  const peak = (s: { start: number; end: number }): number => {
    const moments = [s.start, ...spans.map((o) => o.start).filter((x) => x > s.start && x < s.end)];
    return Math.max(
      ...moments.map(
        (m) => spans.filter((o) => m >= o.start && m < o.end).slice(-STICKER_MAX_LIVE).length,
      ),
    );
  };

  const widths = live.map((s) => {
    const k = Math.min(peak(s), STICKER_MAX_LIVE);
    // Той, хто вже стояв, поступається новому: свіже в кадрі важливіше,
    // і різниця в розмірі каже про це без жодного руху.
    const senior = 1;
    return maxWidthPct * (SHRINK[k] ?? 0.5) * senior;
  });

  // Розводимо по всій смузі, а не ставимо купкою по центру: два предмети
  // поруч у середині кадру читаються як один здвоєний малюнок, і зв'язок
  // між ними («ти» і «твоя програма») зникає. Розведені по краях — вони
  // стають двома учасниками, між якими є відстань, а отже й стосунок.
  const INSET = 0.06;
  if (n === 1) {
    const w = widths[0]!;
    return live.map((s) => ({ ...s, left: (1 - w) / 2, width: w }));
  }
  const widest = Math.max(...widths);
  const step = (1 - INSET * 2 - widest) / (n - 1);
  return live.map((s, i) => ({
    ...s,
    left: INSET + i * step + (widest - widths[i]!) / 2,
    width: widths[i]!,
  }));
}

/**
 * Гальмування: різко почав, плавно зупинився.
 *
 * Для в'їзду з-за краю потрібне саме воно, а не симетрична крива: та
 * розганяється в середині шляху, тобто рівно у видимій частині кадру, і
 * предмет проскакує її ривком.
 */
function easeOut(x: number): number {
  const c = Math.min(Math.max(x, 0), 1);
  return 1 - (1 - c) ** 3;
}

/** Плавний перехід 0→1 без зламу на кінцях. */
function smooth(x: number): number {
  const c = Math.min(Math.max(x, 0), 1);
  return (1 - Math.cos(c * Math.PI)) / 2;
}

export const GLOW_ATTACK_S = 0.09;
export const GLOW_RELEASE_S = 0.34;
/**
 * Рівень спокою. Слово не гасне в нуль після вимови: у кадрі лишається
 * слід щойно сказаного, і рядок читається як мова, а не як текст, де
 * світиться рівно одне слово.
 */
export const GLOW_REST = 0.18;

/**
 * Наскільки слово «звучить» просто зараз, 0…1 (правило
 * `asr-keyword-glow`): наростання за час атаки, утримання до кінця
 * слова, спад до рівня спокою.
 *
 * Це ЧИСТА функція часу — не клас-тригер і не CSS-перехід. Тільки так
 * кадр однаковий при перемотці в обидва боки: перехід памʼятає, звідки
 * їхав, а рендер починає з будь-якої секунди й такої памʼяті не має.
 */
export function wordGlow(t: number, w: WordTiming): number {
  if (t < w.start) return 0;
  if (t < w.end) return Math.min((t - w.start) / GLOW_ATTACK_S, 1);
  const releaseEnd = w.end + GLOW_RELEASE_S;
  if (t < releaseEnd) return 1 - ((t - w.end) / GLOW_RELEASE_S) * (1 - GLOW_REST);
  return GLOW_REST;
}

export const PUNCH_DUR_S = 0.26;

/**
 * Удар кадру на акцентному слові (правило `physics-press-reaction`):
 * стиск → віддача з перельотом → спокій. Повертає ДЕЛЬТУ масштабу,
 * тому нуль означає «нічого не відбувається» і множити нема чого.
 *
 * Стиск займає третину вікна, віддача — решту: вага набирається різко,
 * а віддає предмет довше. Рівна тривалість обох фаз читається як
 * механічне блимання, а не як удар.
 */
export function accentPunch(t: number, words: readonly WordTiming[]): number {
  for (const w of words) {
    if (!w.accent) continue;
    const p = (t - w.start) / PUNCH_DUR_S;
    if (p < 0 || p >= 1) continue;
    if (p < 0.3) return -0.06 * smooth(p / 0.3);
    if (p < 0.6) return -0.06 + 0.16 * smooth((p - 0.3) / 0.3);
    return 0.1 * (1 - smooth((p - 0.6) / 0.4));
  }
  return 0;
}

/*
 * Дрейф стікера — кут, тривалість і фаза за порядковим номером.
 *
 * Раніше всі гойдались однаково і в такт: три предмети читались як одна
 * намальована картинка. Розводимо не випадковим числом, а таблицею за
 * індексом — інакше кадр перемальовувався б інакше на кожному прогоні,
 * і рендер не збігався б із превʼю.
 *
 * Фаза відʼємна: анімація починається вже в середині циклу, тож стікери
 * не стартують синхронно навіть коли зʼявились одночасно.
 */
const DRIFT_TILT_DEG = [2.9, -3.5, 2.4, -3.1, 3.3];
const DRIFT_DUR_S = [1.25, 1.05, 1.45, 1.15, 1.55];
const DRIFT_PHASE_S = [0, -0.5, -0.3, -0.8, -0.35];

/**
 * Детермінований шум: те саме число на вході — той самий результат.
 *
 * `Math.random` тут заборонений принципово: кожен прогін малював би
 * інший кадр, превʼю не збігалося б із рендером, а перемотка назад
 * показувала б не те, що було секунду тому.
 */
export function prand(n: number): number {
  const x = Math.sin(n * 127.1 + 311.7) * 43758.5453;
  return x - Math.floor(x);
}

export const ENTER_S = 0.68;

/**
 * Вхід стікера в кадр — чиста функція віку.
 *
 * `x` — зсув у частках власної ширини, `scale` і `opacity` — як є.
 * Раніше поява жила в CSS-анімації, і через це вхід був один на всіх:
 * ані стати одразу, ані приїхати збоку вона не вміла.
 */
/**
 * Повний стан входу/виходу. Понад базові зсув-масштаб-прозорість —
 * необов'язкові осі для нових ефектів: 2D-нахил, 3D-розворот навколо
 * вертикалі, окремі масштаби по осях (сплюск) і розмиття. Відсутнє
 * поле = нейтральне значення, старі ефекти їх не чіпають.
 */
export interface StickerFx {
  x: number;
  y: number;
  scale: number;
  opacity: number;
  rot?: number;
  ry?: number;
  sx?: number;
  sy?: number;
  blur?: number;
}

export function stickerEnter(
  kind: StickerEnter | undefined,
  age: number,
): StickerFx {
  const k = kind ?? 'pop';
  // Стоїть із першого кадру: жодного зростання, жодного проявлення.
  if (k === 'instant') return { x: 0, y: 0, scale: 1, opacity: 1 };
  const p = Math.min(Math.max(age / ENTER_S, 0), 1);
  // Проявлення на вході: перші 35 % шляху предмет набирає щільність.
  // Доти opacity стрибала 0→1 одним кадром — рух був, а поява ні:
  // предмет ВИСКАКУВАВ у кадр уже щільним, і око ловило стрибок.
  // instant лишається без фейду навмисно — його суть «уже стоїть».
  const fadeIn = smooth(Math.min(p / 0.35, 1));
  if (k === 'from-right' || k === 'from-left') {
    const dir = k === 'from-right' ? 1 : -1;
    // Проскакує ціль на 10 % ширини і повертається: предмет, що
    // зупиняється рівно на місці, читається як приклеєний.
    const x = p < 0.62
      ? dir * (2.2 - 2.42 * easeOut(p / 0.62))
      : dir * (-0.22 + 0.22 * smooth((p - 0.62) / 0.38));
    return { x, y: 0, scale: 1, opacity: fadeIn };
  }
  if (k === 'from-bottom') {
    // Підйом із-під нижнього краю зони, з тим самим проскоком, що й у
    // бічного входу. Для людини це природніший вхід за виростання на
    // місці: фігура приходить у кадр, а не проявляється в ньому.
    const y = p < 0.62
      ? 1.6 - 1.78 * easeOut(p / 0.62)
      : -0.18 + 0.18 * smooth((p - 0.62) / 0.38);
    return { x: 0, y, scale: 1, opacity: fadeIn };
  }
  if (k === 'flip') {
    // Розворот із ребра: предмет стояв боком (90°) і розвертається до
    // глядача з перельотом на −10° — зупинка рівно в нуль читається як
    // механічна. Щільність набирає швидше за інших: ребро й так тонке.
    const ry = p < 0.7
      ? 90 - 100 * easeOut(p / 0.7)
      : -10 + 10 * smooth((p - 0.7) / 0.3);
    return { x: 0, y: 0, scale: 1, opacity: smooth(Math.min(p / 0.25, 1)), ry };
  }
  if (k === 'drop') {
    // Падіння згори: розгін (квадрат — вільне падіння), удар зі
    // сплюском по вертикалі й розширенням по горизонталі, короткий
    // відскок. Сплюск — у вузькому вікні контакту, не розмазаний.
    const y = p < 0.5
      ? -1.35 * (1 - (p / 0.5) ** 2)
      : p < 0.75
        ? -0.2 * Math.sin(Math.PI * ((p - 0.5) / 0.25))
        : 0;
    const contact = p >= 0.48 && p < 0.64
      ? Math.sin(Math.PI * ((p - 0.48) / 0.16))
      : 0;
    return {
      x: 0, y, scale: 1, opacity: fadeIn,
      sy: 1 - 0.18 * contact,
      sx: 1 + 0.1 * contact,
    };
  }
  if (k === 'stamp') {
    // Печатка: завеликий і напівпрозорий притискається в своє місце,
    // в кінці — короткий дотиск нижче одиниці й повернення. Щільність
    // приходить із притиском: штамп «проявляється» від контакту.
    const scale = p < 0.55
      ? 1.6 - 0.6 * easeOut(p / 0.55)
      : p < 0.8
        ? 1 - 0.04 * Math.sin(Math.PI * ((p - 0.55) / 0.25))
        : 1;
    return { x: 0, y: 0, scale, opacity: smooth(Math.min(p / 0.45, 1)) };
  }
  if (k === 'spin') {
    // Виріст із довертанням: нахил −16° розкручується з перельотом на
    // +3° і сідає в нуль. Це вхід, а не «обертання як подія» — кут
    // малий і живе лише всередині появи.
    const rot = p < 0.75
      ? -16 + 19 * easeOut(p / 0.75)
      : 3 - 3 * smooth((p - 0.75) / 0.25);
    const scale = 0.5 + 0.5 * smooth(Math.min(p / 0.8, 1));
    return { x: 0, y: 0, scale, opacity: fadeIn, rot };
  }
  const scale = p < 0.68
    ? 0.8 + 0.26 * smooth(p / 0.68)
    : 1.06 - 0.06 * smooth((p - 0.68) / 0.32);
  return { x: 0, y: 0, scale, opacity: fadeIn };
}

/**
 * Вихід стікера — чиста функція прогресу 0…1 за останні
 * STICKER_EXIT_LEAD_S секунд життя. Повертає МНОЖНИКИ й ДОБАВКИ до
 * стану входу: рендер комбінує вхід·вихід, тому обірваний вхід і
 * ранній вихід складаються без стрибків.
 *
 * `shrink` — історичний вихід «сів і згас» (був єдиним і зашитим).
 */
export function stickerExit(
  kind: StickerExit | undefined,
  outP: number,
): { x: number; y: number; scaleMul: number; opacity: number; rot: number; ry: number; sx: number; sy: number; blur: number } {
  const o = Math.min(Math.max(outP, 0), 1);
  const none = { x: 0, y: 0, scaleMul: 1, opacity: 1, rot: 0, ry: 0, sx: 1, sy: 1, blur: 0 };
  if (o <= 0) return none;
  const k = kind ?? 'shrink';
  if (k === 'flip-out') {
    // Дзеркалить flip-вхід: розворот на ребро в ІНШИЙ бік. Гасне лише
    // в кінці — ребро тонке, і фейд поверх нього подвоював би зникання.
    return {
      ...none,
      ry: -90 * smooth(o),
      opacity: 1 - smooth(Math.max(0, (o - 0.35) / 0.65)),
    };
  }
  if (k === 'drop-out') {
    // Зривається вниз, як упущений: розгін квадратом, легкий нахил у
    // падінні. Прозорість тримається — предмет ПАДАЄ, а не тане.
    return {
      ...none,
      y: 1.5 * o * o,
      rot: 9 * o,
      opacity: 1 - smooth(Math.max(0, (o - 0.4) / 0.6)),
    };
  }
  if (k === 'whoosh-up') {
    // Вилітає вгору, стискаючись по горизонталі — слід від швидкості.
    return {
      ...none,
      y: -1.7 * o * o * o,
      sx: 1 - 0.28 * o,
      opacity: 1 - smooth(Math.max(0, (o - 0.5) / 0.5)),
    };
  }
  if (k === 'dissolve') {
    // Розчинення: трохи виростає, розмивається і тане. Єдиний вихід,
    // де предмет НЕ рухається — тому й читається як спогад, а не дія.
    return {
      ...none,
      scaleMul: 1 + 0.1 * o,
      blur: 7 * o,
      opacity: 1 - smooth(o),
    };
  }
  // shrink: ті самі числа, що жили інлайново в рендері (−12 % масштабу
  // через punch). Перенесено сюди, щоб вихід мав одне джерело правди.
  return { ...none, scaleMul: 1 - 0.12 * o, opacity: 1 - o };
}

/** Скільки бейджів тримаємо над стікером. Більше — стовп замість акценту. */
/**
 * Скільки місця над стікером резервується під бейдж.
 *
 * Заміряно на готовому ролику: плашка займає 84 px висоти плюс ~20 px
 * проміжку до картинки. Без цього запасу предмет із бейджем займав усю
 * зону цілком, а плашка виїжджала над нею — у ролику вона опинялась на
 * 132 px від верху при безпечних 250, тобто рівно під шапкою Instagram.
 */
export const BADGE_ROOM = 0.055;

/**
 * Висота плашки в пікселях полотна — із того самого заміру, що й
 * `BADGE_ROOM`: кегль 4.3 cqw від 1080 (46.4 px) × 1.2 інтерліньяжу
 * плюс поля 0.3em згори й знизу. Потрібна там, де плашку треба сховати
 * ЗА картку: без її висоти не порахувати, наскільки з'їхати вниз.
 */
export const BADGE_H_PX = 84;

/**
 * Півширина плашки і поле від краю кадру — у частках ШИРИНИ кадру.
 *
 * Потрібні, щоб відсунути бічний бейдж від предмета й водночас не дати
 * йому вилізти за край: у частках коробки це не рахується, бо коробка
 * вузького предмета сама стоїть близько до краю.
 */
export const BADGE_HALF = 0.085;
export const BADGE_EDGE = 0.15;

export const BADGE_MAX_LIVE = 3;
export const BADGE_IN_S = 0.42;
/** Скільки бейдж висить, перш ніж піти. */
export const BADGE_HOLD_S = 2.6;
/** Скільки триває відліт угору. */
export const BADGE_OUT_S = 0.5;

/**
 * Бейджі, які вже вилетіли на момент t, від найстарішого до найновішого.
 *
 * Накопичення тут головне: «−10 хв» один раз це факт, три поспіль — це
 * вже відчуття втрати. Тому старий не зникає, коли приходить новий.
 */
export const BADGE_SHIFT_S = 0.28;

export function liveBadges(
  badges: readonly StickerBadge[] | undefined,
  words: readonly WordTiming[],
  t: number,
): { badge: StickerBadge; age: number; rank: number; rankSmooth: number }[] {
  if (!badges?.length) return [];
  const live = badges
    .map((b) => ({ badge: b, age: t - (words[b.at]?.start ?? Number.POSITIVE_INFINITY) }))
    .filter((x) => Number.isFinite(x.age) && x.age >= 0 && x.age < BADGE_HOLD_S + BADGE_OUT_S)
    .slice(-BADGE_MAX_LIVE);
  // Ранг рахується від НАЙНОВІШОГО: він стає просто над предметом, а
  // попередні виштовхуються вище й тануть. Конвеєр читається як «ось
  // що відбувається зараз», а стовп однакових плашок — як список.
  /*
   * Ранг ПЛАВНИЙ. Раніше поява нового бейджа миттєво зсувала ранг усіх
   * попередніх — і вони телепортувались через кадр. Тепер, поки
   * найновіший молодший за BADGE_SHIFT_S, старі стоять між своїм
   * попереднім і новим місцем: та сама чиста функція часу, тільки без
   * стрибка.
   */
  const newestAge = live[live.length - 1]?.age ?? Number.POSITIVE_INFINITY;
  const shift = smooth(Math.min(Math.max(newestAge / BADGE_SHIFT_S, 0), 1));
  return live.map((x, i) => {
    const rank = live.length - 1 - i;
    // Найновіший уже на своєму місці; решта доїжджають зі старого рангу.
    const rankSmooth = rank === 0 ? 0 : rank - 1 + shift;
    return { ...x, rank, rankSmooth };
  });
}

/**
 * Виліт бейджа: з-за стікера вгору, з перельотом і розворотом.
 *
 * Плашка не проявляється на місці, а саме вилітає — інакше вона
 * читається як напис, який хтось домалював, а не як подія, що щойно
 * сталася. Розворот гасне разом із рухом: предмет, що прилетів і лишився
 * перекошеним, виглядає впалим.
 */
export function badgeRankFade(rank: number): number {
  // Другий ряд уже наполовину прозорий, третій майже зник: у кадрі
  // читається лише найсвіжіша плашка, решта — слід.
  return rank <= 0 ? 1 : Math.max(0, 0.5 - (rank - 1) * 0.32);
}

export function badgePop(age: number): {
  opacity: number;
  scale: number;
  lift: number;
  rot: number;
} {
  // Відліт: плашка сказала своє й іде вгору, звільняючи кадр. Без цього
  // вони копичаться до кінця стікера і з акценту стають стовпом.
  if (age >= BADGE_HOLD_S) {
    const gone = smooth(Math.min((age - BADGE_HOLD_S) / BADGE_OUT_S, 1));
    return { opacity: 1 - gone, scale: 1 - 0.2 * gone, lift: -1.4 * gone, rot: 0 };
  }
  const p = Math.min(Math.max(age / BADGE_IN_S, 0), 1);
  const e = smooth(p);
  return {
    opacity: 1,
    scale: 0.6 + 0.4 * e + 0.12 * Math.sin(p * Math.PI),
    lift: (1 - e) * 1.6,
    rot: (1 - e) * -9,
  };
}

/**
 * Те саме, але для плашки на картці колекційного: вона і приходить, і
 * йде ЗА КАРТКУ, тобто вниз.
 *
 * Чому не `badgePop`. Там плашка відлітає ВГОРУ, звільняючи кадр — це
 * правильно, коли під нею предмет із прозорими полями. На картці ж
 * угорі безпечна лінія Instagram, а сама плашка ширша за картку, і
 * будь-який виліт убік або вгору лишає її просто висіти в порожньому
 * полі. Картка ж — суцільний непрозорий блок, і за нього плашка
 * ховається природно: вийшла з-за верхнього краю, сказала своє, пішла
 * назад.
 *
 * Розвороту немає навмисно: плашка виїжджає з-за краю, а не прилітає
 * здалеку, і перекіс читався б як зачеплення.
 */
export function badgePopSlide(age: number): {
  opacity: number;
  scale: number;
  lift: number;
  rot: number;
} {
  if (age >= BADGE_HOLD_S) {
    const gone = smooth(Math.min((age - BADGE_HOLD_S) / BADGE_OUT_S, 1));
    return { opacity: 1 - gone, scale: 1 - 0.04 * gone, lift: gone, rot: 0 };
  }
  const p = Math.min(Math.max(age / BADGE_IN_S, 0), 1);
  const e = smooth(p);
  // Коротке проявлення на старті. Плашка ширша за картку (376–580 px
  // проти 352), тож навіть цілком «схована» вона світить плечима з-за
  // країв — і без цього вони спалахували б одним кадром. За 30 % входу
  // (0.13 с) непрозорість уже повна, тож виїзд лишається виїздом, а не
  // стає проявленням.
  return { opacity: Math.min(1, p / 0.3), scale: 0.96 + 0.04 * e, lift: 1 - e, rot: 0 };
}

export const LABEL_DELAY_S = 0.16;
export const LABEL_IN_S = 0.3;

/**
 * Приліт пігулки під стікером.
 *
 * Виходить ПІСЛЯ картинки, а не разом із нею: одночасний старт двох
 * предметів читається як одна плита, послідовний — як «спершу річ,
 * потім підпис до неї».
 */
export function labelPop(age: number): { opacity: number; scale: number; lift: number } {
  const p = Math.min(Math.max((age - LABEL_DELAY_S) / LABEL_IN_S, 0), 1);
  const eased = smooth(p);
  return {
    // Пігулка теж не проявляється: до свого часу її просто немає, а з
    // ним вона вилітає готовою.
    opacity: p > 0 ? 1 : 0,
    // Переліт на середині шляху — пігулка «сідає» на місце, а не
    // під'їжджає рівно.
    scale: 0.86 + 0.14 * eased + 0.06 * Math.sin(p * Math.PI),
    lift: (1 - eased) * 0.5,
  };
}

export function stickerDrift(
  i: number,
): { tilt: string; dur: string; delay: string; dir: string } {
  const k = ((i % DRIFT_TILT_DEG.length) + DRIFT_TILT_DEG.length) % DRIFT_TILT_DEG.length;
  return {
    tilt: `${DRIFT_TILT_DEG[k] ?? 1.5}deg`,
    dur: `${DRIFT_DUR_S[k] ?? 4.2}s`,
    delay: `${DRIFT_PHASE_S[k] ?? 0}s`,
    // Сусіди пливуть у протилежні боки: коли всі йдуть в один, група
    // читається як одна картинка, що з'їжджає вбік.
    dir: k % 2 === 0 ? '1' : '-1',
  };
}

/**
 * Звідки взялась доріжка.
 *
 * manual    — власник залив готовий mp3 (наприклад з ElevenLabs)
 * generated — зробив scripts/voice.py
 *
 * Різниця не косметична: у manual немає таймкодів, їх треба добути
 * forced alignment, і доти субтитри будувати нема з чого.
 */
export type AudioSource = 'manual' | 'generated';

export interface PostAudio {
  /** Шлях до файлу в проєкті. */
  path: string;
  source: AudioSource;
  /** Тривалість у секундах; 0 — ще не виміряна. */
  duration: number;
  voice?: string;
  engine?: 'edge' | 'eleven';
}

export interface PostSpec {
  version: 1;
  title: string;
  preset: PresetId;
  audio: PostAudio | null;
  /** Текст сценарію — потрібен і для alignment, і для монтажу. */
  script: string;
  words: WordTiming[];
  beats: Beat[];
  /**
   * Розмітка на речення — смислова структура ролика. Може бути
   * відсутньою: ролик, зроблений до неї, лишається робочим, просто
   * картинки в ньому не згруповані в думки.
   */
  scenes?: Scene[];
  /** Може бути відсутнім у ролику, зробленому до появи стікерів. */
  stickers?: Sticker[];
  /** Картки-екрани. Живуть у тій самій смузі, що й стікери. */
  cards?: Card[];
  /**
   * Пришвидшення доріжки. 1 — як записано.
   *
   * Стискає ЧАС: разом із голосом їдуть субтитри, стікери й межі бітів,
   * бо всі вони прив'язані до `words`. Анімації персонажа лишаються на
   * своїй швидкості — виїзд, похитування й зміна пози живуть у власному
   * часі, і пришвидшити їх означало б зробити рухи смиканими.
   *
   * Для Reels це головний важіль довжини: сорокасекундний сценарій на
   * 1.3× стає тридцятисекундним, не втрачаючи жодного слова.
   */
  speed?: number;
}

/**
 * Дозволені множники. Крок 0.1: на слух різниця між 1.15 і 1.2 нічого
 * не вирішує, а вибір із двадцяти позицій перетворює блок на список.
 *
 * Вище 2.0 не піднімаємось — там уже не швидка мова, а нерозбірлива.
 */
export const SPEEDS = [1, 1.1, 1.2, 1.3, 1.4, 1.5, 1.6, 1.7, 1.8, 1.9, 2] as const;

export function emptyPost(title = 'Новий пост'): PostSpec {
  return {
    version: 1,
    title,
    preset: DEFAULT_PRESET,
    audio: null,
    script: '',
    words: [],
    beats: [],
    stickers: [],
    speed: 1,
  };
}


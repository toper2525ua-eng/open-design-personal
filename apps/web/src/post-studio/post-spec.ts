/** Пословний таймкод. Єдине джерело правди для субтитрів. */
export interface WordTiming {
  word: string;
  start: number;
  end: number;
  /**
   * Ключове слово фрази — те, заради якого вона сказана. У кадрі йде на
   * жовтій плашці. Позначається на етапі таймкодів, бо саме там видно
   * увесь текст одразу; у кадрі окремо взяте слово вже не оцінити.
   */
  accent?: boolean;
}

/**
 * Роль речення у сценарії. Від неї залежить РУХ, а не картинка: проблема
 * тремтить, рішення сідає пружиною, перелік накопичується, число
 * приходить ударом. Без ролі анімацію доводиться вигадувати щоразу
 * заново, і кадр виходить різнобоєм.
 */
export type SceneRole = 'hook' | 'problem' | 'mechanism' | 'proof' | 'action' | 'summary';

/** Настрій — теж про рух і колір акценту, не про предмет у кадрі. */
export type SceneMood = 'calm' | 'tension' | 'triumph';

/**
 * Речення — смислова одиниця ролика.
 *
 * ЧОМУ НЕ СЛОВО. Стікер, прив'язаний до слова, живе сам по собі: у кадрі
 * немає поняття «зараз ми говоримо про одну річ», тому картинки й
 * читаються як карусель наліпок. Речення дає межі думки: поки думка
 * триває, група в кадрі одна й та сама і лише добудовується.
 *
 * ЩО ТУТ НЕ ЗБЕРІГАЄТЬСЯ. Ні тексту, ні часу — і те, й те виводиться з
 * `words` за індексами. Дубль тексту розійшовся б із доріжкою після
 * першого ж перезапису таймкодів.
 *
 * Поля змісту (`topic`, `role`, `mood`) заповнює агент, а не студія:
 * саме вони, а не слово під картинкою, є ключем до правильного
 * зображення. «Двісті» дає цифру, хоча речення було про правило «не
 * довше 200 рядків» — і потрібен зовсім інший предмет.
 */
/**
 * Розбір одного речення — рішення агента про те, що буде в кадрі.
 *
 * Живе в даних, а не в голові: наступного разу видно не лише ЩО
 * поставили, а й ЧОМУ саме це. Без записаного «чому» перегенерація
 * ходить по колу й повертає те, що вже забракували.
 */
export interface ScenePlan {
  /** Група картинок · сторінка розмітки · свідома тиша. */
  kind: 'stickers' | 'page' | 'none';
  /** Ідентифікатори стікерів або файл сторінки. */
  items?: string[];
  /** Як рухається — словами, поки словник рухів не заведено. */
  motion?: string;
  /** Чому саме так. Найцінніше поле: воно переживає перегенерацію. */
  why?: string;
}

export interface Scene {
  /** Індекс першого слова у `PostSpec.words`. */
  from: number;
  /** Індекс останнього слова, включно. */
  to: number;
  /** Розбір: що показуємо і чому. Пише агент. */
  plan?: ScenePlan;
  /** Про що річ — іменник, а не переказ. Ключ до картинки. */
  topic?: string;
  role?: SceneRole;
  mood?: SceneMood;
  /**
   * Продовження попередньої думки. Тоді група в кадрі НЕ міняється, а
   * добудовується; нова тема — нова група з переходом. Без цієї ознаки
   * кадр знову перетворюється на карусель.
   */
  continues?: boolean;
  /** Чому саме таке рішення — рядок розкадровки, лишається в даних. */
  why?: string;
}


/**
 * Стікер — картинка, прив'язана до конкретного СЛОВА, а не до біта.
 *
 * Біт триває 4–8 секунд і накриває цілу думку; стікер ілюструє один
 * предмет усередині неї («двісті файлів», «пити воду»). Якби він жив на
 * біті, з'являвся б на початку фрази — задовго до слова, яке малює, і
 * зв'язок між картинкою і текстом розпадався б.
 *
 * Тому час береться з `words[word].start`, тобто з того самого джерела,
 * що й субтитри. Вирівнювати руками нема чого.
 */
export type StickerEnter = 'instant' | 'pop' | 'from-right' | 'from-left';

/**
 * Бейдж — коротка плашка над стікером: «−10 хв», «×3», «{}».
 *
 * Не підпис. Пігулка внизу каже, ЧИЙ предмет («ти», «твій сайт»), а
 * бейдж каже, що з ним ЗАРАЗ відбувається. Тому пігулка одна й висить
 * усю сцену, а бейджів кілька і вони накопичуються.
 */
export interface StickerBadge {
  text: string;
  /** Індекс слова, на якому вилітає. Час — з того самого джерела. */
  at: number;
  /** `warn` — червоний (втрата, помилка) · `info` — синій (подія). */
  tone?: 'warn' | 'info';
}

export interface Sticker {
  /** Ідентифікатор, він же ім'я файлу: `brain-empty` → `brain-empty.svg`. */
  id: string;
  /** Індекс слова у `PostSpec.words`, на якому стікер з'являється. */
  word: number;
  /**
   * Файл у проєкті (`assets/stickers/brain-empty.svg`). Порожньо —
   * стікер запланований, але ще не намальований: панель покаже його
   * як пропуск, кадр просто лишиться без картинки.
   */
  file?: string;
  /**
   * Скільки висить у кадрі, секунди. Не `end`: слово може переїхати
   * після нового дубля, і абсолютний кінець тоді бреше, а тривалість — ні.
   */
  hold: number;
  /**
   * На скільки секунд стати в кадр РАНІШЕ за своє слово.
   *
   * Потрібне рівно в гаку: перше слово ролика звучить не на нулі, і поки
   * до нього дійде, глядач уже бачив порожній кадр. Там картинка має
   * вести, а не ілюструвати. Далі по ролику — навпаки, і поле лишається
   * порожнім.
   */
  lead?: number;
  /** Що зображено — підпис у панелі й бриф для малювання. */
  note?: string;
  /**
   * Як заходить у кадр.
   *
   * `instant` — стоїть із першого кадру сцени. Перший стікер думки має
   * бути саме таким: поки він виростає, глядач дивиться на порожнечу,
   * а на початку речення цих часток секунди й вирішується, чи він
   * лишиться.
   * `pop` — виростає з перельотом (звичайний вхід усередині сцени).
   * `from-right` / `from-left` — виїжджає з-за краю кадру. Так заходить
   * ДРУГИЙ предмет, коли перший уже стоїть: рух іззовні читається як
   * поява нової дійової особи, а не як підміна картинки.
   */
  enter?: StickerEnter;
  /**
   * Дрібні плашки, що злітають над стікером і НАКОПИЧУЮТЬСЯ («−10 хв»
   * ×3). Саме вони роблять кадр живим при одній картинці: предмет
   * стоїть, а стан навколо нього змінюється.
   */
  badges?: StickerBadge[];
  /**
   * Пігулка під стікером — два-три слова, які картинка сама сказати не
   * може: число, назва, умова («не довше 200 рядків»).
   *
   * Це НЕ дубль субтитра. Субтитр несе те, що зараз звучить, і зникає
   * разом із фразою; пігулка висить рівно поки висить стікер і
   * договорює саме його. Порожньо — стікер іде без підпису, і це
   * нормальний стан, а не незаповнене поле.
   */
  label?: string;
}

/**
 * Картка — екран або документ, намальований кодом.
 *
 * ЧОМУ НЕ СТІКЕР. Термінал, код, чек-лист, дерево файлів — усе це
 * інтерфейс, а не предмет. Згенерована картинка терміналу дає розмитий
 * мультик, де текст не читається й не масштабується; та сама картка в
 * розмітці дає справжній моноширинний рядок, чіткий на будь-якому
 * кеглі, і головне — рядки можуть відкриватись ПІД МОВУ, чого растр не
 * вміє в принципі.
 *
 * Правило поділу просте: предмет або метафору (ракета, крапля, лампочка)
 * малює модель і це стікер; екран, документ або цифру малює розмітка і
 * це картка.
 *
 * КАРТКУ МАЛЮЄ АГЕНТ, А НЕ СТУДІЯ. Тут навмисно немає ні видів, ні полів
 * під зміст: щойно студія задає «вікно / список / метрика», малює вже
 * вона, а агент лише заповнює чужі графи. Тоді все, чого в графах не
 * передбачили, зробити неможливо.
 *
 * Тому картка — це файл розмітки, який агент пише сам під конкретну
 * фразу (`assets/blocks/<id>.html`), а студія знає про нього рівно три
 * речі: коли показати, скільки тримати і як анімувати появу.
 *
 * ДОГОВІР ПРО ПОЯВУ РЯДКІВ. Усередині розмітки будь-який елемент можна
 * позначити `data-reveal` — студія відкриватиме такі елементи по черзі
 * під мову, додаючи їм клас `is-shown`. Як саме виглядає закритий і
 * відкритий стан, вирішує CSS самої картки. Це єдине, що студія
 * нав'язує, і воно про ЧАС, а не про вигляд.
 */
export interface Card {
  id: string;
  /** Слово, на якому картка зʼявляється. Джерело часу те саме — words. */
  word: number;
  /** Скільки висить, секунди. */
  hold: number;
  /** Файл розмітки в проєкті: `assets/blocks/<id>.html`. */
  file: string;
  /** Що на картці, одним рядком — підпис у панелі. */
  note?: string;
}

/**
 * Скільки позначених `data-reveal` елементів уже видно на момент t.
 *
 * Відкриваються рівномірно, а не всі одразу: готовий список глядач
 * прочитає до того, як про нього скажуть, і далі слухатиме вже без
 * інтересу. Останню чверть відрізка тримаємо на повному складі — щоб
 * фінальний рядок встиг прочитатись.
 */
export function cardRevealCount(total: number, hold: number, start: number, t: number): number {
  if (total <= 0) return 0;
  const fill = Math.max(0.001, hold * 0.75);
  const k = Math.floor(((t - start) / fill) * total) + 1;
  return Math.max(1, Math.min(total, k));
}

/** Активна картка на позиції t. Двох одночасно не буває — вони широкі. */
export function cardAt(
  cards: readonly Card[],
  words: readonly WordTiming[],
  t: number,
): { card: Card; start: number; end: number } | null {
  const spans = cards
    .filter((c) => words[c.word] != null && c.hold > 0)
    .map((c) => ({ card: c, start: words[c.word]!.start, end: words[c.word]!.start + c.hold }))
    .sort((a, b) => a.start - b.start);
  // Остання з тих, що вже почались і ще не скінчились: якщо агент
  // накидав карток внахлест, у кадрі буде найсвіжіша, а не найстаріша.
  let found: { card: Card; start: number; end: number } | null = null;
  for (const s of spans) {
    if (s.start <= t && t < s.end) found = s;
  }
  return found;
}


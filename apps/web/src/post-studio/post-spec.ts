export const POST_FILE_RE = /(^|\/)post\.json$/i;
export const AUDIO_RE = /\.(mp3|wav|m4a|aac|ogg|opus)$/i;
/**
 * `.json` тут — Lottie: стікер, який несе власну анімацію всередині
 * файлу. Растр лишається дозволеним, але це вже мертва картинка, весь
 * рух якої доводиться домальовувати ззовні.
 */
export const STICKER_RE = /(^|[\\/])assets[\\/]stickers[\\/][^\\/]+\.(svg|png|webp|json)$/i;

/**
 * Готовність ролика до наступного кроку. Студія показує це замість
 * того, щоб мовчки малювати порожній кадр.
 */
export function postStage(post: PostSpec): 'audio' | 'align' | 'beats' | 'ready' {
  if (!post.audio) return 'audio';
  if (post.words.length === 0) return 'align';
  if (post.beats.length === 0) return 'beats';
  return 'ready';
}

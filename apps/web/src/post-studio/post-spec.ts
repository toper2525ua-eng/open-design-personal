export interface Sticker {
  /** Ідентифікатор, він же ім'я файлу: `brain-empty` → `brain-empty.svg`. */
  id: string;
  /** Індекс слова у `PostSpec.words`, на якому стікер з'являється. */
  word: number;
  /**
   * Файл у проєкті (`assets/stickers/brain-empty.svg`). Порожньо —
   * стікер запланований, але ще не намальований: панель покаже його
   * як пропуск, кадр просто лишиться без картинки.
   */
  file?: string;
  /**
   * Скільки висить у кадрі, секунди. Не `end`: слово може переїхати
   * після нового дубля, і абсолютний кінець тоді бреше, а тривалість — ні.
   */
  hold: number;
  /**
   * На скільки секунд стати в кадр РАНІШЕ за своє слово.
   *
   * Потрібне рівно в гаку: перше слово ролика звучить не на нулі, і поки
   * до нього дійде, глядач уже бачив порожній кадр. Там картинка має
   * вести, а не ілюструвати. Далі по ролику — навпаки, і поле лишається
   * порожнім.
   */
  lead?: number;
  /** Що зображено — підпис у панелі й бриф для малювання. */
  note?: string;
  /**
   * Як заходить у кадр.
   *
   * `instant` — стоїть із першого кадру сцени. Перший стікер думки має
   * бути саме таким: поки він виростає, глядач дивиться на порожнечу,
   * а на початку речення цих часток секунди й вирішується, чи він
   * лишиться.
   * `pop` — виростає з перельотом (звичайний вхід усередині сцени).
   * `from-right` / `from-left` — виїжджає з-за краю кадру. Так заходить
   * ДРУГИЙ предмет, коли перший уже стоїть: рух іззовні читається як
   * поява нової дійової особи, а не як підміна картинки.
   * `flip` — розворот із ребра (був повернутий боком, став обличчям).
   * `drop` — падає згори зі сплюском при ударі.
   * `stamp` — печатка: завеликий і прозорий притискається в місце.
   * `spin` — виростає з довертанням проти годинникової.
   */
  enter?: StickerEnter;
  /**
   * Як іде з кадру. Порожньо — `shrink`, історичний «сів і згас».
   * `flip-out` — розвертається на ребро (дзеркалить flip-вхід).
   * `drop-out` — зривається вниз із нахилом, як упущений.
   * `whoosh-up` — вилітає вгору, стискаючись, як запущений.
   * `dissolve` — розчиняється з розмиттям: для «минулого» і «мрій».
   */
  exit?: StickerExit;
  /**
   * Предмет стоїть мертво: без дрейфу і дихання. Для кадрів, де рух
   * несе орнамент (смайли по орбіті) — два рухи разом дають кашу.
   */
  still?: boolean;
  /**
   * Файл — спрайт-аркуш: сітка кадрів у одному PNG, кадр вибирається
   * з віку предмета (seek-safe, як LottieSticker). Це шлях для
   * Telegram-емодзі (TGS): lottie-web їх мовчки НЕ малює — рендерить
   * rlottie у кадри, кадри клеяться в аркуш.
   */
  sprite?: StickerSprite;
  /**
   * Орнамент НАВКОЛО предмета — живе і вмирає разом із ним.
   * `arrows` — рукописні стрілки з боків, що вказують на предмет
   * («дивись сюди»); `satellites` — дрібні кружечки, що розлітаються
   * з-за предмета і висять поруч («навколо нього щось відбувається»).
   */
  ornament?: StickerOrnament;
  /**
   * Зв'язка з ІНШИМ живим стікером (`from` — його id): `arrow` — дуга
   * від нього до цього («стає», «веде до»), `sparks` — іскри конфлікту
   * посередині («сваряться»). Малюється, лише поки живі обидва.
   */
  link?: StickerLink;
  /**
   * Дрібні плашки, що злітають над стікером і НАКОПИЧУЮТЬСЯ («−10 хв»
   * ×3). Саме вони роблять кадр живим при одній картинці: предмет
   * стоїть, а стан навколо нього змінюється.
   */
  badges?: StickerBadge[];
  /**
   * Пігулка під стікером — два-три слова, які картинка сама сказати не
   * може: число, назва, умова («не довше 200 рядків»).
   *
   * Це НЕ дубль субтитра. Субтитр несе те, що зараз звучить, і зникає
   * разом із фразою; пігулка висить рівно поки висить стікер і
   * договорює саме його. Порожньо — стікер іде без підпису, і це
   * нормальний стан, а не незаповнене поле.
   */
  label?: string;
  /**
   * Синя пігулка ПРИСВОЮЄ предмет глядачеві («ти», «твій сайт»), червона
   * його ТАВРУЄ («завелика», «складні промпти»). Це два різні
   * висловлювання, і колір тут несе сенс, а не оформлення: синім
   * помічене — твоє, червоним — те, що заважає.
   */
  labelTone?: 'own' | 'warn';
}

/**
 * Картка — екран або документ, намальований кодом.
 *
 * ЧОМУ НЕ СТІКЕР. Термінал, код, чек-лист, дерево файлів — усе це
 * інтерфейс, а не предмет. Згенерована картинка терміналу дає розмитий
 * мультик, де текст не читається й не масштабується; та сама картка в
 * розмітці дає справжній моноширинний рядок, чіткий на будь-якому
 * кеглі, і головне — рядки можуть відкриватись ПІД МОВУ, чого растр не
 * вміє в принципі.
 *
 * Правило поділу просте: предмет або метафору (ракета, крапля, лампочка)
 * малює модель і це стікер; екран, документ або цифру малює розмітка і
 * це картка.
 *
 * КАРТКУ МАЛЮЄ АГЕНТ, А НЕ СТУДІЯ. Тут навмисно немає ні видів, ні полів
 * під зміст: щойно студія задає «вікно / список / метрика», малює вже
 * вона, а агент лише заповнює чужі графи. Тоді все, чого в графах не
 * передбачили, зробити неможливо.
 *
 * Тому картка — це файл розмітки, який агент пише сам під конкретну
 * фразу (`assets/blocks/<id>.html`), а студія знає про нього рівно три
 * речі: коли показати, скільки тримати і як анімувати появу.
 *
 * ДОГОВІР ПРО ПОЯВУ РЯДКІВ. Усередині розмітки будь-який елемент можна
 * позначити `data-reveal` — студія відкриватиме такі елементи по черзі
 * під мову, додаючи їм клас `is-shown`. Як саме виглядає закритий і
 * відкритий стан, вирішує CSS самої картки. Це єдине, що студія
 * нав'язує, і воно про ЧАС, а не про вигляд.
 */
/**
 * Міні-стікер НА картці (підглянуто в референсів: суддя на куті посту,
 * трійця на краю плашки). Сідає на порожнє місце картки на своєму
 * слові і живе до її кінця. `spot` вибирає АГЕНТ, дивлячись, де в
 * розмітці порожньо — центр стікера стає на край/кут, тож половина
 * навмисно виступає за картку, як наліпка.
 */
export type CardStickerSpot = 'tl' | 'tr' | 'bl' | 'br' | 'l' | 'r';
export type CardStickerFrom = 'right' | 'left' | 'top';
export interface CardSticker {
  /** Файл стікера з набору проєкту. */
  file: string;
  /** Слово, на якому стікер сідає. Джерело часу те саме — words. */
  word: number;
  /** Де на картці порожньо. Дефолт — правий нижній кут. */
  spot?: CardStickerSpot;
  /** Ширина в частках ширини картки. Дефолт 0.16. */
  size?: number;
  /**
   * Звідки влітає: з-за правого краю екрана, лівого чи згори. Порожньо —
   * за місцем: лівим spot'ам зліва, правим справа. Вліт через усю
   * картку (лівий spot справа) — теж легальний хід, але свідомий.
   */
  from?: CardStickerFrom;
}

export const CARD_STICKER_IN_S = 0.55;

/**
 * Вліт наліпки на картку: З-ЗА ПРАВОГО КРАЮ екрана до свого місця,
 * справа наліво. Повертає прогрес шляху: 1 — ще за екраном, 0 — на
 * місці; проскакує ціль на 6 % і повертається — зупинка рівно на місці
 * читається як приклеєна. Політ фізичний, тому без фейду.
 */
export function cardStickerFly(age: number): number {
  const p = Math.min(Math.max(age / CARD_STICKER_IN_S, 0), 1);
  return p < 0.62
    ? 1 - 1.06 * easeOut(p / 0.62)
    : -0.06 + 0.06 * smooth((p - 0.62) / 0.38);
}

